begin;

create table if not exists public.waitlist (
  id bigint generated by default as identity primary key,
  size text not null check (size in ('XS', 'S', 'M', 'L', 'XL', 'XXL', 'undecided')),
  city text not null default 'Qeyd edilməyib',
  contact_type text not null check (contact_type in ('email', 'phone')),
  contact text not null unique check (char_length(contact) between 3 and 254),
  consent_version text not null,
  consented_at timestamptz not null default now()
);

alter table public.waitlist enable row level security;
revoke all on table public.waitlist from public, anon, authenticated, service_role;
grant select, insert on table public.waitlist to service_role;
grant usage on sequence public.waitlist_id_seq to service_role;

commit;
